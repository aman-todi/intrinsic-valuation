def normalize_sic(sic_code: str | int | None) -> str | None:
    """Return the SIC code as a zero-padded 4-digit string, or ``None`` if it isn't one."""
    if sic_code is None:
        return None
    s = str(sic_code).strip()
    if not s.isdigit() or len(s) > 4:
        return None
    return s.zfill(4)


def industry_for_sic(sic_code: str | int | None) -> str | None:
    """Map a SIC code to a Damodaran industry name (4-digit, then 3-, then 2-digit prefix)."""
    sic = normalize_sic(sic_code)
    if sic is None:
        return None
    return SIC4.get(sic) or SIC3.get(sic[:3]) or SIC2.get(sic[:2])


def all_mapped_industries() -> set[str]:
    return set(SIC4.values()) | set(SIC3.values()) | set(SIC2.values()) | {TOTAL_MARKET}
