"""Offline demo data (``DATA_SOURCE_MODE=fixtures``).

The ``edgar/`` directory holds the hand-built SEC-format fixtures (companyfacts / submissions /
company_tickers, plus one segment XBRL instance) generated by ``tests/fixtures/edgar/build_fixtures.py``.
They are the canonical copy: the unit tests load them from here, and the worker serves them in demo
mode through :class:`app.data.demo.edgar_client.FixtureEdgarClient`, so the app can run end to end
with no network access to SEC / Yahoo / FRED.

Demo market data is deterministic: a fixed price and share count per ticker and a fixed risk-free rate.
Every run built in this mode carries :data:`DEMO_DATA_FLAG` in its data-confidence flags.

Never enable this mode in a deployed environment.
"""

