@cache
def _read(name: str) -> str:
    return (DEMO_EDGAR_DIR / name).read_text()


def has_file(name: str) -> bool:
    return (DEMO_EDGAR_DIR / name).is_file()


def load_companyfacts(ticker: str) -> dict[str, Any]:
    """Fresh (mutable) copy of ``{TICKER}_companyfacts.json``."""
    return json.loads(_read(f"{ticker.upper()}_companyfacts.json"))


def load_submissions(ticker: str) -> dict[str, Any]:
    return json.loads(_read(f"{ticker.upper()}_submissions.json"))


def load_company_tickers() -> dict[str, Any]:
    return json.loads(_read("company_tickers.json"))


def segments_document(ticker: str) -> bytes | None:
    """The latest 10-K's XBRL instance with segment facts, when the fixture set has one."""
    path = DEMO_EDGAR_DIR / f"{ticker.upper()}_segments_instance.xml"
    return path.read_bytes() if path.is_file() else None


def fixture_tickers() -> tuple[str, ...]:
    """Tickers with a submissions fixture (the ones demo mode can serve), sorted."""
    return tuple(
        sorted(p.name.removesuffix("_submissions.json") for p in DEMO_EDGAR_DIR.glob("*_submissions.json"))
    )
